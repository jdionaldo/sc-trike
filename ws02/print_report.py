"""Output side of print_prep: plate 3MFs, overview images, report.json and PRINT_PLAN.md."""
import json
from collections import defaultdict
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Polygon as MPoly, Rectangle
import numpy as np

import print_prep as PP

OUT = PP.OUT
PLAN = Path("PRINT_PLAN.md")
COL = {"PETG": "#6fa8dc", "PETG-CF": "#555555"}


def plate_stats(pl, rowmap):
    mass = hours = 0.0
    for it, rot, sh, poly in pl["placed"]:
        r = rowmap[it.name]
        mass += r["mass_g"]
        hours += r["hours"]
    return mass, hours


def settings_for(it, r):
    rec = it.recipe
    d = {"layer_height": rec.layer, "wall_loops": rec.walls, "sparse_infill_density": f"{rec.infill}%",
         "sparse_infill_pattern": "gyroid", "top_shell_layers": rec.top, "bottom_shell_layers": rec.bottom}
    if r["support"]["kind"] != "none":
        d.update(enable_support=1, support_top_z_distance=r["support"]["zgap"], support_on_build_plate_only=int(r["support"].get("plate_only", False)))
    return d


def write_plates(plates, rowmap):
    for f in list(OUT.glob("plate_*.3mf")) + list(OUT.glob("plate_*.png")):
        f.unlink()
    for i, pl in enumerate(plates, 1):
        objs, sets = [], []
        for it, rot, sh, poly in pl["placed"]:
            m = PP.placed_mesh(it, rot, sh)
            objs.append((f"{it.name}_{it.inst + 1}" if it.recipe.qty > 1 else it.name, m))
            sets.append(settings_for(it, rowmap[it.name]))
        PP.write_3mf(OUT / f"plate_{i:02d}.3mf", objs, sets)


def draw_plate(ax, i, pl, rowmap):
    ax.add_patch(Rectangle((0, 0), 256, 256, fc="#f4f4f4", ec="k"))
    ax.add_patch(Rectangle((PP.EXCLUDE[0], PP.EXCLUDE[1]), PP.EXCLUDE[2], PP.EXCLUDE[3], fc="#e8b0b0", ec="none", alpha=0.7))
    ax.add_patch(Rectangle((PP.EDGE, PP.EDGE), 256 - 2 * PP.EDGE, 256 - 2 * PP.EDGE, fc="none", ec="#999", ls=":"))
    for it, rot, sh, poly in pl["placed"]:
        m = PP.placed_mesh(it, rot, sh)
        fp = PP.footprint(m)
        xy = np.array(fp.exterior.coords)
        ax.add_patch(MPoly(xy, fc=COL[it.recipe.material], ec="k", alpha=0.85, lw=0.6))
        c = fp.centroid
        ax.text(c.x, c.y, it.name.replace("w3_", "").replace("body3_", "skin_") + f"\n{m.extents[2]:.0f} high", ha="center", va="center", fontsize=5.5)
    mass, hrs = plate_stats(pl, rowmap)
    mat, lay, col = pl["key"]
    ax.set_title(f"Plate {i:02d}  {mat} {lay} mm  {col}\n{len(pl['placed'])} parts  {mass:.0f} g  {hrs:.1f} h", fontsize=8)
    ax.set_xlim(-2, 258)
    ax.set_ylim(-2, 258)
    ax.set_aspect("equal")
    ax.set_xticks([0, 128, 256])
    ax.set_yticks([0, 128, 256])
    ax.tick_params(labelsize=6)


def write_images(plates, rowmap):
    n = len(plates)
    cols = min(4, n)
    rows = -(-n // cols)
    fig, axs = plt.subplots(rows, cols, figsize=(4.6 * cols, 5.0 * rows), squeeze=False)
    for ax in axs.ravel():
        ax.axis("off")
    for i, pl in enumerate(plates, 1):
        ax = axs.ravel()[i - 1]
        ax.axis("on")
        draw_plate(ax, i, pl, rowmap)
        f2, a2 = plt.subplots(figsize=(6, 6.4))
        draw_plate(a2, i, pl, rowmap)
        f2.savefig(OUT / f"plate_{i:02d}.png", dpi=110, bbox_inches="tight")
        plt.close(f2)
    fig.suptitle("WS03 print plates, Bambu Lab P2S 256 x 256 mm (red = assumed wipe corner, dotted = 4 mm edge margin)", fontsize=10)
    fig.tight_layout()
    fig.savefig(OUT / "overview.png", dpi=110)
    plt.close(fig)


def fmt_holes(r):
    bad = [h for h in r["holes"] if h["kind"] == "hole" and h["verdict"] not in ("ok",)]
    return bad


def write_plan(rows, plates, failed, missing, orphans, rowmap):
    L = []
    A = L.append
    A("# WS03 print plan (Bambu Lab P2S, 0.4 mm nozzle)\n")
    A("Generated by `python print_prep.py` from the current `out/stl` and `out/mono3` STLs. Do not edit by hand; rerun the command.\n")
    A("## Printer and plate\n")
    A("- Bambu Lab P2S build volume 256 x 256 x 256 mm (Bambu wiki). The usable area used here is **248 x 248 mm** (4 mm edge margin), height **250 mm**, 6 mm between parts.")
    A("- A wipe/purge exclusion corner of 22 x 32 mm at the front left is assumed (the X1/P1 profile has 18 x 28 mm; no P2S figure was found in public pages). Check the plate view in Bambu Studio and move parts if the grey exclusion zone is bigger.")
    A("- PETG-CF needs a hardened-steel 0.4 mm nozzle (the stock stainless one wears quickly); dry PETG/PETG-CF 65 C 6 h before printing.\n")
    A("## Plates\n")
    A("| plate | parts | material | layer | walls | infill | top/bottom | supports | brim | est. g | est. h |")
    A("|---|---|---|---|---|---|---|---|---|---|---|")
    for i, pl in enumerate(plates, 1):
        rs = [rowmap[it.name] for it, *_ in pl["placed"]]
        names = []
        for it, *_ in pl["placed"]:
            names.append(it.name.replace("w3_", "") + (f"#{it.inst + 1}" if it.recipe.qty > 1 else ""))
        mat, lay, col = pl["key"]
        wl = sorted({r["walls"] for r in rs})
        inf = sorted({r["infill"] for r in rs})
        tb = sorted({f"{r['top']}/{r['bottom']}" for r in rs})
        sup = sorted({r["support"]["kind"] for r in rs})
        brim = "5 mm brim" if any(r["height"] / max(min(r["bbox"][0], r["bbox"][1]), 1) > 2.0 or r["flat_mm2"] < 120 for r in rs) else "none"
        mass, hrs = plate_stats(pl, rowmap)
        A(f"| {i:02d} ({col}) | {', '.join(names)} | {mat} | {lay} | {'-'.join(map(str, wl))} | gyroid {min(inf)}-{max(inf)}% (per part, see below) | {', '.join(tb)} | {', '.join(sup)} | {brim} | {mass:.0f} | {hrs:.1f} |")
    tm = sum(plate_stats(p, rowmap)[0] for p in plates)
    th = sum(plate_stats(p, rowmap)[1] for p in plates)
    A(f"\n**{len(plates)} plates, about {tm:.0f} g and {th:.0f} h in total** (estimates from volume: walls + infill + 15 % dense supports, 10 mm3/s PETG, 8 mm3/s PETG-CF, x1.35 overhead; real times are typically within 20 %).\n")
    A("Speed notes: outer wall 60 mm/s and 0.2 mm layers for visible skin; 100 to 150 mm/s inner; PETG-CF inner wall 80 mm/s; first layer 30 mm/s, bed 70 C (PETG) / 80 C (CF), nozzle 250 / 260 C; part cooling 30-50 %; no ironing; seam aligned at the back; arachne walls. Slow to 50 mm/s on the 0.16 mm gear-housing plate. All 3MFs carry per-object wall/infill/layer/support values in `Metadata/model_settings.config` (Bambu keys); if Studio ignores them, use the table below.\n")
    A("## Material choice\n")
    A("- **PETG-CF** (frame, rear swing arm, front arms, carriers/knuckles, gear housings, motor plate, wing hangers): stiffer (about 1.5x flexural modulus), less creep and a higher heat deflection under the motor; layer adhesion is lower, so the layers are aligned with the load where the geometry allows. CF parts use a 0.2 mm support gap, 2 interface layers (CF does not weld to the support).")
    A("- **PETG** (skin, decks, wing blade, trays, links, small spacers): tougher (impact), better layer adhesion, glossy skin, cheaper. Supports on PETG use 0.25 mm gap and 3 interface layers; PETG bonds hard to PETG so the interface must stay loose.")
    A("- Never PLA near the motor or in the sun. ASA is an acceptable skin substitute (needs an enclosure; the P2S has one).\n")
    A("## Support strategy (easy peel)\n")
    A("- Threshold 45 deg; support only where the overhang is beyond that. Supports on the build plate only for visible/skin faces (flag per part below).")
    A("- Trusses and arms: **tree (slim)**, branch angle 40 deg, tip diameter 1.2 mm. Plates, trays, flat parts with local overhangs: **normal (snug)**.")
    A("- Top Z distance 0.25 mm (PETG) / 0.2 mm (PETG-CF); bottom Z distance 0.2 mm; interface layers 3 (PETG) / 2 (CF); top interface pattern rectilinear, interface spacing 0.2 mm (loose), base pattern rectilinear 2.5 mm spacing; XY distance 0.5 mm (use 0.35 mm near bearing seats).")
    A("- Brim: 5 mm (outer, 0.1 mm gap) only on tall/narrow parts or those with under 120 mm2 on the bed; mouse ears not needed.\n")
    A("## Parts: orientation, supports, mass\n")
    A("| part | qty | plate | material | orientation (up vector in STL frame) | bbox mm (x,y,z) | bed contact mm2 | overhang % | support mm3 | support type | walls/infill | g each | h each | fits as one |")
    A("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    plate_of = {}
    for i, pl in enumerate(plates, 1):
        for it, *_ in pl["placed"]:
            plate_of[it.name] = i
    for r in rows:
        A(f"| {r['name']} | {r['qty']} | {plate_of.get(r['name'], '-')} | {r['material']} | {np.round(r['up'], 2).tolist()} | {r['bbox']} | {r['flat_mm2']} | {r['overhang_pct']} | {r['support_mm3']} | {r['support']['text']} | {r['walls']}/{r['infill']}% | {r['mass_g']} | {r['hours']} | {'yes' if r['fits_unsplit'] else 'SPLIT'} |")
    A("\nOrientation is the best of up to 40 candidates (axes, large flat faces, hull faces, tilts about the long axis) by cost = 3 x support volume/part volume + 2 x overhang area share + 0.6 x (1 - bed contact) + 0.6 x height/250 + 1.5 x layer-vs-load penalty (long axis vertical) + a stability term. The up vector is the STL-frame direction that becomes +Z. The transform of each is in `out/print/report.json`.\n")
    A("## Strength notes\n")
    A("| part | walls | infill | note |")
    A("|---|---|---|---|")
    for r in rows:
        A(f"| {r['name']} | {r['walls']} | gyroid {r['infill']}% | {PP.strength_note(r)} |")
    A("\nHigher infill (45 to 50 %) on the frame, arms, hangers, motor plate and shock mounts; tubes are solid, so print them with the axis in the bed plane (layers along the tube). Heat-set M2/M3 inserts: 4 walls and 5 top/bottom layers around them.\n")
    A("## Thinnest sections (ray test from 2500 surface samples)\n")
    A("`p1` is the 1st percentile wall thickness (robust); `min` can be a tangential-ray artefact at tube joints. Flags: p1 under 1.2 mm, gaps under 0.8 mm (3 or more samples).\n")
    A("| part | min mm | p1 mm | p5 mm | % samples < 1.2 mm | narrowest gap mm | gap samples < 0.8 | flag |")
    A("|---|---|---|---|---|---|---|---|")
    for r in rows:
        t = r["thickness"]
        flag = []
        if t["p1"] < PP.PC.WALL_MIN:
            flag.append(f"thin wall near {t['thin_at']}")
        if t["gap_count"] >= 3:
            flag.append(f"narrow gap near {t['gap_at']}")
        A(f"| {r['name']} | {t['min']:.2f} | {t['p1']:.2f} | {t['p5']:.2f} | {100 * t['frac_thin']:.1f} | {t['gap_min']:.2f} | {t['gap_count']} | {'; '.join(flag) or '-'} |")
    A("\n## Mesh integrity (trimesh)\n")
    bad = [r for r in rows if r["topo"]["problems"]]
    if not bad:
        A("All parts: single watertight manifold, consistent winding, positive volume.\n")
    else:
        A("| part | problems found | after safe repair (in memory only, STL files untouched) |")
        A("|---|---|---|")
        for r in bad:
            A(f"| {r['name']} | {'; '.join(r['topo']['problems'])} | {'; '.join(r['topo_after']['problems']) or 'clean'} ({', '.join(r['repaired'])}) |")
        A("")
    A("## Holes and fits to check\n")
    A("Detected cylindrical holes whose diameter is at the nominal screw/bearing/magnet size (no clearance) or does not match a known fit. Targets: M2 clear 2.4, M2.5 pilot 2.0-2.2 (self-tap) or clear 2.7-2.9, M2 insert 3.0-3.3, M3 clear 3.4, M3 insert 4.2, 5 mm shaft 5.2, magnet 6x2 pocket 6.2-6.3 (2.1 deep), 5x11x4 bearing seat 11.15-11.3 (4.1 deep), 8x16x5 seat 16.15-16.3. Vertical holes print about 0.1 mm small, horizontal ones about 0.1 mm oval.\n")
    A("| part | hole d mm | axis | verdict |")
    A("|---|---|---|---|")
    cnt = 0
    for r in rows:
        seen = set()
        for h in fmt_holes(r):
            key = (h["dia"], h["verdict"])
            if key in seen:
                continue
            seen.add(key)
            n = sum(1 for g in r["holes"] if (g["dia"], g["verdict"]) == key)
            A(f"| {r['name']} | {h['dia']} (x{n}) | {np.round(h['axis'], 1).tolist()} | {h['verdict']} |")
            cnt += 1
    if not cnt:
        A("| - | - | - | none |")
    A("\nSideways pegs (unsupported overhangs) and thin features:\n")
    for r in rows:
        for p in r["pegs"]:
            A(f"- {r['name']}: peg d{p['dia']} x {p['length']} mm at {p['centre']} (axis {np.round(p['axis'], 1).tolist()})")
    A("")
    A("## Suggested geometry changes (not applied; part files untouched)\n")
    any_s = False
    for r in rows:
        for s in r["suggestions"]:
            A(f"- {s}")
            any_s = True
    if not any_s:
        A("- none")
    A("")
    A("## Splits\n")
    sp = [r for r in rows if r["split"]]
    if not sp:
        A("No part exceeds the plate in its best orientation. Skin pieces front/mid/rear, frame front/rear, decks front/rear/tail and the wing main/right already fit one plate each. If a future skin or frame is too big, `propose_split()` cuts across the longest axis at the thinnest section near the middle and adds up to 3 pegs (4 mm x 6 mm, 0.2 mm clearance per side).")
    for r in sp:
        A(f"- {r['source']}: cut at {r['split']['axis']} = {r['split']['pos']:.1f} mm, {r['split']['pegs']} pegs d{r['split']['peg_d']} x {r['split']['peg_len']} mm, clearance {r['split']['fit']} mm; pieces printed on their own.")
    A("")
    A("## Missing, failed, orphaned\n")
    A(f"- Missing STL: {', '.join(n for n, _ in missing) or 'none'}")
    A(f"- Failed in the pipeline: {', '.join(f'{n} ({e})' for n, e in failed) or 'none'}")
    A(f"- STL files in out/stl that no current part writes (stale, delete or ignore): {', '.join(orphans) or 'none'}")
    A("- Skin STLs not printed (stale or intermediate): body3.stl, body3_left/right*, lid3.stl, shell*.stl, skin*.stl, solid.stl.")
    PLAN.write_text("\n".join(L) + "\n")


def write_all(rows, plates, failed, missing, orphans):
    OUT.mkdir(parents=True, exist_ok=True)
    rowmap = {r["name"]: r for r in rows}
    write_plates(plates, rowmap)
    write_images(plates, rowmap)
    pj = []
    for i, pl in enumerate(plates, 1):
        pj.append(dict(plate=i, key=list(pl["key"]), parts=[dict(name=it.name, inst=it.inst, rot=rot, shift=list(sh), height=float(it.mesh.extents[2]),
                                                                  bounds=list(poly.bounds)) for it, rot, sh, poly in pl["placed"]]))
    slim = [{k: v for k, v in r.items() if k != "holes"} for r in rows]
    (OUT / "report.json").write_text(json.dumps(dict(parts=slim, plates=pj, failed=failed, missing=[n for n, _ in missing], orphans=orphans), indent=1, default=str))
    write_plan(rows, plates, failed, missing, orphans, rowmap)
    print(f"{len(plates)} plates; parts {len(rows)}; failed {len(failed)}; missing {[n for n, _ in missing]}")
