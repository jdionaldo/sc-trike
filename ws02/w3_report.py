"""Writes WS03_REPORT.md: printed parts table (size, volume, mass), totals and the design numbers."""
import glob, os
import numpy as np
import trimesh
import w3_parts, w3_scene as S
from parts import w3_front as W

rows = []
names = [p.name for p in w3_parts.all_parts()]
for n in names:
    f = f"out/stl/{n}.stl"
    if os.path.exists(f):
        t = trimesh.load(f)
        rows.append((n, np.round(t.extents, 1).tolist(), abs(t.volume) / 1000.0))
for n in [f"body3_{p}" for p in ("front", "mid", "rear")]:
    f = f"{__import__('skin_cfg').MONO}/{n}.stl"
    if os.path.exists(f):
        t = trimesh.load(f)
        rows.append((n, np.round(t.extents, 1).tolist(), abs(t.volume) / 1000.0))
qty = {"w3_arm_left": 1, "w3_tie_rod": 2, "w3_lean_rod": 2, "w3_batt_tray": 1, "w3_esc_tray": 1}
dens = 1.27
tot = 0.0
lines = ["# WS-03 report (3WD lean-steer reverse trike)", "", "Generated by `w3_report.py`. Mass is volume x 1.27 g/cc (solid; real prints are lighter with infill).", "",
         "| part | size mm | volume cm3 | mass g |", "|---|---|---|---|"]
for n, ext, v in rows:
    k = qty.get(n, 1)
    tot += v * dens * k
    lines.append(f"| {n}{' x' + str(k) if k > 1 else ''} | {ext[0]} x {ext[1]} x {ext[2]} | {v:.1f} | {v * dens * k:.0f} |")
lines += ["", f"Printed total (solid, one set; left/right pairs listed separately): about {tot:.0f} g.", "",
          "## Design numbers", "",
          f"- Front track {2 * S.F.T:.0f} mm (wheel centres), wheelbase 450 mm, front tires 83 x 24, rear 112 x 62.",
          "- Lean limit 25 deg, arm length 100 mm, arm swing about 40 deg, steering +-17 deg (radio mix), 4 servos (lean and steer per front wheel).",
          "- Chassis raked 4 deg nose-down; shaft line at the front axle height, y +21.",
          "- Gearing: motor 15T to centre diff ring 45T (3:1), bevel 12T/30T (2.5:1) at both ends, front belt 20T to 16T, rear belt 20T to 22T.",
          "- Pose sweep: lean -25..+25 with steer 0, +17, -17: no interference (tests/test_w3.py)."]
open("WS03_REPORT.md", "w").write("\n".join(lines) + "\n")
print(len(rows), "parts, about", round(tot), "g")
